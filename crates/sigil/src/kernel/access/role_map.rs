use super::Role;

macro_rules! role_map {
    ($($role:ident),+ $(,)?) => {
        impl Role {
            pub(crate) const fn native(self) -> accesskit::Role {
                match self {
                    Self::Unknown => accesskit::Role::Unknown,
                    $(Self::$role => accesskit::Role::$role,)+
                }
            }

            /// The role of a node in the tree from `Host::accessibility_tree`.
            #[must_use]
            pub const fn from_accesskit(role: accesskit::Role) -> Self {
                match role {
                    $(accesskit::Role::$role => Self::$role,)+
                    _ => Self::Unknown,
                }
            }
        }
    };
}

